"""Evidence Provenance and Integrity Layer.

Enforces unambiguous, falsifiable categorization of evidence sources and prevents
unsubstantiated claims (e.g. labeling geometric fallbacks as independent AI models,
treating human bounding boxes as proof of object identity, or treating user-supplied
metadata as independently verified observations).
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field


class ProvenanceCategory(str, Enum):
    REAL_PHOTOGRAPH = "REAL_PHOTOGRAPH"
    PUBLIC_DATASET_ANNOTATION = "PUBLIC_DATASET_ANNOTATION"
    HUMAN_ANNOTATION = "HUMAN_ANNOTATION"
    MODEL_PREDICTION = "MODEL_PREDICTION"
    GEOMETRIC_FALLBACK = "GEOMETRIC_FALLBACK"
    SYNTHETIC_FIXTURE = "SYNTHETIC_FIXTURE"
    USER_SUPPLIED_METADATA = "USER_SUPPLIED_METADATA"
    VERIFIED_TEMPORAL_OBSERVATION = "VERIFIED_TEMPORAL_OBSERVATION"


class ProvenanceViolationError(ValueError):
    """Raised when an evidence source category or verification claim is contradicted by actual context."""
    pass


# Alias for backward compatibility
ProvenanceViolation = ProvenanceViolationError


class EvidenceProvenance(BaseModel):
    category: ProvenanceCategory
    source_identifier: str = Field(..., description="Unique hash, dataset ID, or session identifier")
    source_url: Optional[str] = Field(None, description="Official origin URL where applicable")
    license_type: Optional[str] = Field(None, description="Dataset or asset license")
    author_attribution: Optional[str] = Field(None, description="Author attribution string")
    model_identifier: Optional[str] = Field(None, description="Model ID if generated by model")
    verification_method: str = Field(..., description="Technique used to verify this evidence item")
    is_independently_verified: bool = Field(False, description="True if evidence was independently audited")
    dimensions: Optional[tuple[int, int]] = Field(None, description="Image width, height if applicable")
    metadata: Dict[str, Any] = Field(default_factory=dict)


class ProvenanceGate:
    """Enforces evidence provenance integrity rules across the system."""

    @staticmethod
    def audit_claim(
        provenance_or_category: EvidenceProvenance | ProvenanceCategory,
        claimed_effect_or_engine: str,
        has_real_image_bytes: bool = False,
        has_temporal_sequence: bool = False,
        is_user_metadata_only: bool = False,
    ) -> bool:
        """Validates that an evidence item supports a specific claim or operational role."""
        if isinstance(provenance_or_category, EvidenceProvenance):
            prov = provenance_or_category
            cat = prov.category
            claim = claimed_effect_or_engine.upper()

            # Rule 1: A geometric bounding-box fallback must never be labeled independent segmentation
            if cat == ProvenanceCategory.GEOMETRIC_FALLBACK and "INDEPENDENT_SEGMENTATION" in claim:
                raise ProvenanceViolationError(
                    "Violation: Geometric fallback cannot claim independent segmentation."
                )

            # Rule 2: A human-supplied bounding box must never automatically prove object identity
            if cat == ProvenanceCategory.HUMAN_ANNOTATION and "PROVED_OBJECT_IDENTITY" in claim:
                raise ProvenanceViolationError(
                    "Violation: Human-supplied bounding box cannot prove physical object identity without independent verification."
                )

            # Rule 3: One sharp image must not prove physical rest or release
            if cat == ProvenanceCategory.REAL_PHOTOGRAPH and ("PROVED_PHYSICAL_REST" in claim or "PROVED_RELEASE" in claim):
                raise ProvenanceViolationError(
                    "Violation: Single static photograph cannot prove physical rest or release without temporal verification."
                )

            # Rule 4: A user-supplied instruction_followed flag must not independently prove instruction compliance
            if cat == ProvenanceCategory.USER_SUPPLIED_METADATA and "INDEPENDENT_COMPLIANCE" in claim:
                raise ProvenanceViolationError(
                    "Violation: User-supplied metadata cannot independently prove instruction compliance without verified media observation."
                )

            return True

        else:
            cat = provenance_or_category
            actual_engine = claimed_effect_or_engine

            # Engine context checks
            if actual_engine in ("GEOMETRIC_FALLBACK", "deterministic-bounding-box-v1") and cat == ProvenanceCategory.MODEL_PREDICTION:
                raise ProvenanceViolationError(
                    "Violation: A geometric bounding-box fallback cannot be labeled as independent MODEL_PREDICTION."
                )

            if cat == ProvenanceCategory.REAL_PHOTOGRAPH and not has_real_image_bytes:
                raise ProvenanceViolationError(
                    "Violation: REAL_PHOTOGRAPH claimed but no valid image bytes were provided or decoded."
                )

            if cat == ProvenanceCategory.VERIFIED_TEMPORAL_OBSERVATION and not has_temporal_sequence:
                raise ProvenanceViolationError(
                    "Violation: VERIFIED_TEMPORAL_OBSERVATION claimed without verified temporal stream or timestamps."
                )

            if is_user_metadata_only and cat in (ProvenanceCategory.REAL_PHOTOGRAPH, ProvenanceCategory.VERIFIED_TEMPORAL_OBSERVATION):
                raise ProvenanceViolationError(
                    "Violation: User-supplied follow-up metadata cannot claim photographic or temporal observation status without submitted media."
                )

            return True

    @staticmethod
    def build_provenance_record(
        category: ProvenanceCategory,
        source_id: str,
        verification_method: str,
        model_id: Optional[str] = None,
        license_type: Optional[str] = None,
        author: Optional[str] = None,
        url: Optional[str] = None,
        is_verified: bool = False,
        dimensions: Optional[tuple[int, int]] = None,
        **extra_meta: Any,
    ) -> EvidenceProvenance:
        """Constructs a validated EvidenceProvenance object."""
        return EvidenceProvenance(
            category=category,
            source_identifier=source_id,
            source_url=url,
            license_type=license_type,
            author_attribution=author,
            model_identifier=model_id,
            verification_method=verification_method,
            is_independently_verified=is_verified,
            dimensions=dimensions,
            metadata=extra_meta,
        )
